import { ShieldCheck, Sparkles, Loader2 } from 'lucide-react'
import { useWorkspace, useAssistantEnable } from '../hooks/useAnalytics'
import { Alert } from './ui'

/** The disclosure an admin must accept before any data is sent to the AI provider. Used on the Assistant page and in Settings. */
export default function AiConsent({ status }) {
  const { data: ws } = useWorkspace()
  const enable = useAssistantEnable()
  const isAdmin = ws?.role === 'admin'
  const error = enable.error?.response?.data?.detail

  return (
    <div style={{ display: 'grid', gap: 16 }}>
      <div style={{ display: 'grid', gap: 12, gridTemplateColumns: 'repeat(auto-fit, minmax(260px, 1fr))' }}>
        <div className="card tone-success" style={{ background: 'var(--surface-2)', boxShadow: 'none' }}>
          <div className="stat-label" style={{ color: 'var(--tone)', marginBottom: 8 }}>What is sent</div>
          <p style={{ fontSize: 13.5, color: 'var(--text-2)' }}>
            Aggregated, fintech-level facts: fintech names, regions and types, volumes, transaction counts, risk scores and the reasons behind them,
            plus your current findings and health score.
          </p>
        </div>
        <div className="card tone-danger" style={{ background: 'var(--surface-2)', boxShadow: 'none' }}>
          <div className="stat-label" style={{ color: 'var(--tone)', marginBottom: 8 }}>What is never sent</div>
          <p style={{ fontSize: 13.5, color: 'var(--text-2)' }}>
            Your Blockradar API key, wallet addresses, transaction hashes, email addresses, or anything about your team.
          </p>
        </div>
      </div>
      <p className="hint" style={{ display: 'flex', gap: 8, alignItems: 'flex-start' }}>
        <ShieldCheck size={15} style={{ flexShrink: 0, marginTop: 2 }} />
        <span>Answers are generated by Claude, an AI model from Anthropic, using only the data above. It can be wrong, so check important details before acting. You can turn this off at any time.</span>
      </p>
      {error && <Alert tone="danger">{error}</Alert>}
      {status?.available === false ? (
        <Alert tone="info">The AI assistant isn't set up on this server yet. Once the operator adds an Anthropic API key, you'll be able to turn it on here.</Alert>
      ) : isAdmin ? (
        <div>
          <button className="btn btn-primary" onClick={() => enable.mutate(true)} disabled={enable.isPending}>
            {enable.isPending ? <Loader2 size={15} className="spin" /> : <Sparkles size={15} />} Turn on Ask ERNIE for this workspace
          </button>
        </div>
      ) : (
        <Alert tone="info">Ask a workspace admin to turn this on.</Alert>
      )}
    </div>
  )
}
